import random
def generate_numbers(amount,lowest,highest):
  numbers=[]
  for _ in range(amount):
    numbers.append(random.randint(lowest,highest))
  return numbers
def sort_numbers(numbers):
  numbers.sort()
  return numbers
amount=10
lowest=1
highest=100
my_numbers=generate_numbers(amount,lowest,highest)
print("Random Numbers: ",my_numbers)
sorted_numbers=sort_numbers(my_numbers)
print("Sorted Numbers: ",sorted_numbers)